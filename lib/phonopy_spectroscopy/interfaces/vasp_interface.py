def _parse_dielectric_constant(file_path, parent):
    """Parse a dielectric constant in a vasprun.xml file.

    Parameters
    ----------
    file_path : str
        vasprun.xml file being read (used for error messages).
    parent : xml.etree.ElementTree.Element
        XML node containing a dielectric constant.

    Returns
    -------
    eps : numpy.ndarray
        Dielectric constant (shape: `(3, 3)`).
    """

    elements = parent.findall("./v")

    if len(elements) != 3:
        raise RuntimeError(
            f"vasprun.xml file {file_path}: Unexpected number of rows "
            "in dielectric constant element."
        )

    eps = [[float(v) for v in e.text.strip().split()] for e in elements]

    for r in eps:
        if len(r) != 3:
            raise RuntimeError(
                f"vasprun.xml file {file_path}: Unexpected number of "
                "columns in dielectric constant element."
            )

    return np.array(eps, dtype=np.float64)


def _parse_dielectric_function(file_path, parent):
    """Parse a dielectric function in a vasprun.xml file.

    Parameters
    ----------
    file_path : str
        vasprun.xml file being read (used for error messages).
    parent : xml.etree.ElementTree.Element
        XML node containing a dielectric function.

    Returns
    -------
    eps : tuple of numpy.ndarray
        Tuple of `(e, eps_e)` containing a complex dielectric function
        (shapes: `(O,)`, `(O, 3, 3)`).
    """

    # We should have real and imaginary parts containing arrays of
    # values.

    eps_re = parent.findall("./real/array")
    eps_im = parent.findall("./imag/array")

    if len(eps_re) != 1 or len(eps_im) != 1:
        raise RuntimeError(
            f"vasprun.xml file {file_path}: Multiple or missing "
            "real/imag child elements in parent dielectric function "
            "element."
        )

    eps_re, eps_im = eps_re[0], eps_im[0]

    # Check field names are as expected.

    for arr in eps_re, eps_im:
        fields = arr.findall("./field")

        for f, h in zip(
            fields, ["energy", "xx", "yy", "zz", "xy", "yz", "zx"]
        ):
            if f.text != h:
                raise RuntimeError(
                    f"vasprun.xml file {file_path}: Unexpected column "
                    "headings in dielectric function arrays."
                )

    # Check the real and imaginary parts have the same number of rows
    # and that both have at least one row.

    eps_re_rows = eps_re.findall("./set/r")
    eps_im_rows = eps_im.findall("./set/r")

    if len(eps_im_rows) != len(eps_re_rows) or len(eps_re_rows) == 0:
        raise RuntimeError(
            f"vasprun.xml file {file_path}: Real/imaginary dielectric "
            "function arrays of unequal or zero length."
        )

    # Check that each row has the expected number of columns before
    # converting to NumPy arrays.

    eps_re = [[float(v) for v in r.text.strip().split()] for r in eps_re_rows]
    eps_im = [[float(v) for v in r.text.strip().split()] for r in eps_im_rows]

    for r in chain(eps_re, eps_im):
        if len(r) != 7:
            raise RuntimeError(
                f"vasprun.xml file {file_path}: Real/imaginary "
                "dielectric function has unexpected number of columns."
            )

    eps_re = np.array(eps_re, dtype=np.float64)
    eps_im = np.array(eps_im, dtype=np.float64)

    # Check real and imaginary parts are on the same energy axis.

    if not np.allclose(eps_re[:, 0], eps_im[:, 0]):
        raise RuntimeError(
            f"vasprun.xml file {file_path}: Real/imaginary dielectric "
            "function arrays have different energy axes."
        )

    # Extract energies.

    e = eps_re[:, 0]

    # Reconstruct the complex dielectric function from the upper
    # triangle.

    eps_tri = eps_re[:, 1:] + 1.0j * eps_im[:, 1:]

    # Note that VASP outputs elements in the order
    # (xx, yy, zz, xy, yz, zx = xz), but from_upper_triangle() expects
    # (xx, yy, zz, xy, xz, yz).

    eps_tri[:, [4, 5]] = eps_tri[:, [5, 4]]

    return DielectricFunction.from_upper_triangle(e, eps_tri, e_units="ev")


def _try_read_eps_hf(file_path, root):
    """Search for and read a high-frequency dielectric constant from a
    parsed vasprun.xml file.

    Parameters
    ----------
    file_path : str
        File being read (used for error messages).
    parent : xml.etree.ElementTree.Element
        Root node for the parsed file.

    Returns
    -------
    eps : numpy.ndarray or None
        Dielectric constant (shape: `(3, 3)`) or `None` if not found.
    """

    # Look for (single) high-frequency dielectric constants. Depending
    # on the type of calculation, there may be multiple values. The code
    # below is designed so that the last one written to the file is
    # returned, which is usually what we want.

    eps_hf = None

    xpath_strs = [
        # DFPT with LEPSILON = .TRUE.
        './calculation/varray[@name="dielectric_ipa"]',
        './calculation/varray[@name="dielectric_dft"]',
        './calculation/varray[@name="epsilon"]',
        # Finite field with LCALCEPS = .TRUE.
        './calculation/varray[@name="epsilon_scf"]',
        './calculation/varray[@name="dielectric_scf"]',
    ]

    for xpath_str in xpath_strs:
        elements = root.findall(xpath_str)

        if len(elements) > 0:
            if len(elements) == 1:
                eps_hf = _parse_dielectric_constant(file_path, elements[0])
            else:
                raise RuntimeError(
                    f"vasprun.xml file {file_path}: Multiple "
                    "high-frequency dielectric constant calculations "
                    "of the same type."
                )

    return eps_hf


def dielectric_from_vasprun_xml(
    file_path, response_func_type="d-d", response_func_idx=0
):
    """Read high-frequency dielectric constants or energy-dependent
    dielectric functions from a vasprun.xml file.

    Parameters
    ----------
    file_path : str
        File path.
    response_func_type : {"d-d", "c-c"}, optional
        For energy-dependent response functions, sets which type of
        response function to return: density-density (`"d-d"`) or
        current-current (`"c-c"`) (default: `"d-d"`).
    response_func_idx : int, optional
        For vasprun.xml files where response functions are not tagged
        with comments indicating the type, specifies the zero-based
        index of the function to return (default: 0).

    Returns
    -------
    eps : DielectricFunction
        Dielectric function.
    """

    tree = ET.parse(file_path)
    root = tree.getroot()

    eps_hf = _try_read_eps_hf(file_path, root)

    if eps_hf is not None:
        return DielectricFunction(
            np.array([0.0], dtype=np.float64),
            np.array([eps_hf], dtype=np.float64),
            e_units="ev",
        )

    # Look for frequency-dependent dielectric function calculations.
    # Depending on the calculations there may be "density-density" and
    # "current-current" response functions. Which of these is returned
    # is set by an optional argument that defaults to the former.

    elements = root.findall("./calculation/dielectricfunction")

    for element in elements:
        if "comment" in element.attrib:
            if (
                element.attrib["comment"] == "density-density"
                and response_func_type == "d-d"
            ):
                return _parse_dielectric_function(file_path, element)

            if (
                element.attrib["comment"] == "current-current"
                and response_func_type == "c-c"
            ):
                return _parse_dielectric_function(file_path, element)

    # In some vasprun.xml files, the response functions are not tagged
    # with comments indicating their type. In this case, select based
    # on the index specified by response_func_idx.

    if len(elements) > 0:
        if response_func_idx < len(elements):
            return _parse_dielectric_function(
                file_path, elements[response_func_idx]
            )
        else:
            raise RuntimeError(
                f"vasprun.xml file {file_path} : "
                f"response_func_idx={response_func_idx} is not "
                "compatible with the number of dielectric functions "
                f"found in the file ({len(elements)})."
            )

    raise RuntimeError(
        f"vasprun.xml file {file_path} : No dielectric "
        "constants/functions found. This may be because the type of "
        "calculation is not currently supported."
    )


def eps_inf_and_born_from_vasprun_xml(file_path):
    """Read the high-frequency dielectric constant and Born effective
    charges from a vasprun.xml file.

    Parameters
    ----------
    file_path : str
        File path.

    Returns
    -------
    eps_born : tuple of numpt.ndarray
        A `(eps, born)` tuple with the high-frequency dielectric
        constant (shape: `(3, 3)`) and Born charges (shape:
        `(N, 3, 3)`).
    """

    tree = ET.parse(file_path)
    root = tree.getroot()

    eps_hf = _try_read_eps_hf(file_path, root)

    if eps_hf is None:
        raise RuntimeError(
            f"vasprun.xml file {file_path} : High-frequency dielectric "
            "constant not found."
        )

    born_charges = None

    elements = root.findall('./calculation/array[@name="born_charges"]')

    if len(elements) == 1:
        born_charges = []

        for child_set in elements[0].findall("./set"):
            child_v = child_set.findall("./v")

            if len(child_v) != 3:
                raise RuntimeError(
                    f"vasprun.xml file {file_path} : Unexpected "
                    "number of rows in Born charge tensors element."
                )

            z = [[float(v) for v in e.text.strip().split()] for e in child_v]

            for r in z:
                if len(r) != 3:
                    raise RuntimeError(
                        f"vasprun.xml file {file_path}: Unexpected "
                        "number of columns in Born charge tensors "
                        "element."
                    )

            born_charges.append(z)

    if born_charges is None:
        raise RuntimeError(
            f"vasprun.xml file {file_path}: No Born charges or "
            "multiple sets of Born charges found."
        )

    return (eps_hf, np.array(born_charges, dtype=np.float64))


