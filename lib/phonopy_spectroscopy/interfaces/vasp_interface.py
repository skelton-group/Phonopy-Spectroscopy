def gamma_phonons_from_vasp(
    struct_file,
    freqs_evecs_file,
    born_file=None,
    **kwargs,
):
    r"""Read a complete VASP phonon calculation and return a
    `GammaPhonons`, `PolarGammaPhonons` or `FullPolarGammaPhonons`
    object.

    Parameters
    ----------
    struct_file : str
        POSCAR file to read a structure from.
    freqs_evecs_file : str
        OUTCAR file to read phonon frequencies/eigenvectors from.
    born_file : str, optional
        vasprun.xml file to read high-frequency dielectric constant
        \eps_inf and Born effective charges from (default: `None`).
    **kwargs : any, optional
        Keyword arguments for reading structure.

    Returns
    -------
    gamma_ph : `GammaPhonons`, `PolarGammaPhonons` or `FullPolarGammaPhonons`
        Object containing the calculation data.

    Notes
    -----
    If `freqs_evecs_file` contains a "complete" phonon calculation with
    M = 3N frequencies/eigenvectors and `born_file` is set, the function
    returns a `FullPolarGammaPhonons` object. For "partial" calculations
    with M < 3N, it returns a `PolarGammaPhonons` or `GammaPhonons`
    depending on whether `born_file` is set.
    """

    # Read structure.

    struct = structure_from_poscar(struct_file, **kwargs)

    # Read frequencies/eigenvectors.

    freqs, evecs = freqs_evecs_from_outcar(freqs_evecs_file)

    eps_inf, born_charges = None, None

    if born_file is not None:
        # Read high-frequency dielectric constant and Born charges.

        eps_inf, born_charges = eps_inf_and_born_from_vasprun_xml(born_file)

    return get_gamma_phonons(
        struct,
        freqs,
        evecs,
        eps_inf=eps_inf,
        born_charges=born_charges,
        lws=None,
        irreps=None,
        t=None,
    )


