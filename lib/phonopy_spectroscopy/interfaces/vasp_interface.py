def freqs_evecs_from_outcar(file_path):
    """Read Gamma-point phonon frequencies and eigenvectors from an
    OUTCAR file.

    Parameters
    ----------
    file_path : str
        Input file.

    Returns
    -------
    freqs_evecs : tuple of numpy.ndarray
        A `(freqs, evecs)` tuple of arrays with shapes `(M,)` and
        `(M, N, 3)`.

    Notes
    -----
    This function will parse "selective" phonon calculations with
    M < 3N.
    """

    freqs, evecs = None, None

    with open(file_path, "r") as f:
        # Scan for the section header.

        hdr = "Eigenvectors and eigenvalues of the dynamical matrix"

        for line in f:
            if line.strip() == hdr:
                break

        # Skip "horizontal rule" + two blank lines.

        for _ in range(3):
            next(f)

        freqs, evecs = [], []

        freq_regex = re.compile(
            r"(?P<n>\d+)\s*(?P<type>f(/i)?)\s*=\s*(?P<freq>\d+\.\d*)\s*THz"
        )

        evec_hdrs = ("X", "Y", "Z", "dx", "dy", "dz")

        while True:
            match = freq_regex.search(next(f))

            if not match:
                # End of data.
                break

            mode_num = int(match.group("n"))
            mode_type = match.group("type")
            mode_freq = float(match.group("freq"))

            if mode_num != len(freqs) + 1:
                raise RuntimeError(
                    f"OUTCAR file {file_path} : Invalid or corrupt "
                    "frequency line."
                )

            match mode_type:
                case "f":
                    pass
                case "f/i":
                    mode_freq *= -1.0
                case _:
                    raise RuntimeError(
                        f"OUTCAR file {file_path} : Unexpected "
                        "frequency line format."
                    )

            freqs.append(mode_freq)

            if tuple(next(f).strip().split()) != evec_hdrs:
                raise RuntimeError(
                    f"OUTCAR file {file_path} : Unexpected eigenvector "
                    "block header."
                )

            mode_evec = []

            for line in f:
                vals = line.strip().split()

                match len(vals):
                    case 0:
                        evecs.append(mode_evec)
                        break
                    case 6:
                        mode_evec.append([float(v) for v in vals[-3:]])
                    case _:
                        raise RuntimeError(
                            f"OUTCAR file {file_path} : Unexpected "
                            "eigenvector block format."
                        )

    # Check at least one frequency/eigenvector was recovered.

    if freqs is None or len(freqs) == 0:
        raise RuntimeError(
            f"OUTCAR file {file_path} : No frequencies/eigenvectors found."
        )

    # All eigenvectors should have shape (N, 3).

    n_a = len(evecs[0])

    for evec in evecs[1:]:
        if len(evec) != n_a:
            raise RuntimeError(
                f"OUTCAR file {file_path} : Inconsistent number of "
                "entries in eigenvectors."
            )

    freqs = np.array(freqs, dtype=np.float64)
    evecs = np.array(evecs, dtype=np.float64)

    # Eigenvector components are printed to 6 d.p., so a tolerance of
    # 1e-5 should be "safe" for checking normalisation.

    evec_norms = np.linalg.norm(evecs.reshape((len(freqs), -1)), axis=1)

    if not np.allclose(evec_norms, 1.0, atol=1.0e-5):
        raise RuntimeError(
            f"OUTCAR file {file_path} : Eigenvectors are not normalised."
        )

    # VASP usually outputs frequencies/eigenvectors in order of
    # descending frequency. To make it consistent with Phonopy, sort
    # them into frequency order.

    inds = np.argsort(freqs)

    freqs = freqs[inds]
    evecs = evecs[inds]

    return (freqs, evecs)
