def load_json(file_path):
    """Load a JSON-format file and return a Python data structure.

    Parameters
    ----------
    file_path : str
        File path.

    Returns
    -------
    data : any
        Python object containing parsed data.
    """

    with open(file_path, "r") as f:
        return json.load(f)


def save_json(obj, file_path):
    """Save a Python data structure to a JSON-format file.

    Parameters
    ----------
    obj : any
        Python object to save.
    file_path : str
        File path.
    """

    with open(file_path, "w") as f:
        json.dump(obj, f)


def load_yaml(file_path):
    """Load a YAML-format file and return a Python data structure.

    Parameters
    ----------
    file_path : str
        File path.

    Returns
    -------
    data : any
        Python object containing parsed data.
    """

    with open(file_path, "rb") as f:
        return yaml.load(f, Loader=Loader)


def complex_array_to_dict(a):
    """Serialise a complex array to a dictionary of native Python types.

    Parameters
    ----------
    a : array_like
        Array.

    Returns
    -------
    d : dict
        Dictionary containing the array data as native Python types.

    See Also
    --------
    dict_to_complex_array : Deserialise a complex array serialised with
        this function.

    Notes
    -----
    The real and imaginary parts of `a` are stored under `d["real"]` and
    `d["imag"]`, and the latter is stored only if `a` is complex.
    """

    a = np.asanyarray(a)

    d = {"real": a.real.tolist()}

    if np.iscomplexobj(a):
        d["imag"] = a.imag.tolist()

    return d


def dict_to_complex_array(d):
    """Deserialise a dictionary generated by `complex_array_to_dict()`
    to a complex array.

    Parameters
    ----------
    d : dict
        Dictionary containing the data to deserialise.

    Returns
    -------
    a : numpy.ndarray
        Array.

    See Also
    --------
    complex_array_to_dict : Serialise a complex array to a dictionary
        of native Python types.

    Notes
    -----
    `d` should contain `"real"` and, optionally, `"imag"` keys with the
    same data shape. If the `"imag"` key is not present, this function
    returns a real array - this mirrors the serialisation behaviour of
    `complex_array_to_dict()`.
    """

    a = np.asanyarray(d["real"], dtype=np.float64)

    if "imag" in d:
        a_im = np.asanyarray(d["imag"], dtype=np.float64)

        if a_im.shape != a.shape:
            raise RuntimeError(
                'd contains "real" and "imag" keys with different "'
                "array shapes."
            )

        a = a + 1.0j * a_im

    return a
